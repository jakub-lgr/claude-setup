#!/usr/bin/env python3
"""Build catalog.md for the ecc-router skill from a local ECC checkout.

Usage: python build-catalog.py [ECC_ARCHIVE]   (default: $ECC_ARCHIVE or ~/ecc)

One line per agent, skill, command and rule, so the router can grep it instead
of loading hundreds of descriptions into every session. Hooks are left out on
purpose: they can only be enabled when a session starts.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAX_DESC = 180


def frontmatter(path):
    """Minimal YAML frontmatter reader: top-level `key: value`, quoted values and block scalars."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end < 0:
        return {}, text
    lines = text[3:end].strip("\n").splitlines()
    data, i = {}, 0
    while i < len(lines):
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", lines[i])
        i += 1
        if not m:
            continue
        key, value = m.group(1), m.group(2).strip()
        if value in (">", "|", ">-", "|-", ">+", "|+"):
            block = []
            while i < len(lines) and (lines[i].startswith((" ", "\t")) or not lines[i].strip()):
                block.append(lines[i].strip())
                i += 1
            value = " ".join(b for b in block if b)
        elif len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        data[key] = value
    return data, text[end + 4:]


def clean(text):
    text = re.sub(r"\s+", " ", text or "").replace("|", "/").strip()
    return text if len(text) <= MAX_DESC else text[: MAX_DESC - 1].rstrip() + "…"


def skill_flags(folder, body):
    flags = []
    files = [os.path.join(r, n) for r, _, ns in os.walk(folder) for n in ns]
    if any(f.endswith((".py", ".js", ".mjs", ".cjs", ".ts", ".sh", ".ps1")) for f in files):
        flags.append("scripts")
    if "mcp__" in body:
        flags.append("mcp")
    if re.search(r"\bhooks?\.json\b|PreToolUse|PostToolUse|SessionStart", body):
        flags.append("hooks")
    if any(os.path.basename(f).upper().startswith(("LICENSE", "LICENCE")) for f in files):
        flags.append("own-license")
    if len(files) > 1:
        flags.append(f"{len(files)} files")
    return ", ".join(flags) or "-"


def main():
    root = os.path.abspath(os.path.expanduser(
        sys.argv[1] if len(sys.argv) > 1 else os.environ.get("ECC_ARCHIVE", "~/ecc")))
    if not os.path.isdir(os.path.join(root, "agents")):
        sys.exit(f"Not an ECC checkout: {root}")
    try:
        commit = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"],
                                capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"

    rows = []
    for name in sorted(os.listdir(os.path.join(root, "agents"))):
        if not name.endswith(".md"):
            continue
        meta, _ = frontmatter(os.path.join(root, "agents", name))
        info = f'{meta.get("model", "-")}; {meta.get("tools", "-").replace(" ", "")}'
        rows.append(("agent", meta.get("name", name[:-3]), f"agents/{name}", info, clean(meta.get("description"))))

    skills_dir = os.path.join(root, "skills")
    for name in sorted(os.listdir(skills_dir)):
        path = os.path.join(skills_dir, name, "SKILL.md")
        if not os.path.isfile(path):
            continue
        meta, body = frontmatter(path)
        rows.append(("skill", meta.get("name", name), f"skills/{name}/SKILL.md",
                     skill_flags(os.path.join(skills_dir, name), body), clean(meta.get("description"))))

    commands_dir = os.path.join(root, "commands")
    for name in sorted(os.listdir(commands_dir)):
        if name.endswith(".md"):
            meta, _ = frontmatter(os.path.join(commands_dir, name))
            rows.append(("command", name[:-3], f"commands/{name}", "-", clean(meta.get("description"))))

    rules_dir = os.path.join(root, "rules")
    for lang in sorted(os.listdir(rules_dir)):
        folder = os.path.join(rules_dir, lang)
        if not os.path.isdir(folder):
            continue
        for name in sorted(os.listdir(folder)):
            if name.endswith(".md"):
                meta, body = frontmatter(os.path.join(folder, name))
                title = next((l.lstrip("# ").strip() for l in body.splitlines() if l.startswith("#")), name[:-3])
                rows.append(("rule", f"{lang}/{name[:-3]}", f"rules/{lang}/{name}", "-", clean(title)))

    out = os.path.join(HERE, "catalog.md")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# ECC catalog\n\n")
        f.write(f"Generated by build-catalog.py from https://github.com/affaan-m/ecc at commit `{commit}`.\n")
        f.write("Descriptions are ECC's own (MIT, see THIRD_PARTY_NOTICES.md in claude-setup). Paths are relative to the ECC archive.\n\n")
        f.write("kind | name | path | model; tools (agents) or flags (skills) | description\n")
        for r in rows:
            f.write(" | ".join(r) + "\n")
    counts = {k: sum(1 for r in rows if r[0] == k) for k in ("agent", "skill", "command", "rule")}
    print(f"Wrote {out}: {counts}")


if __name__ == "__main__":
    main()
