#!/usr/bin/env bash
# Copies the third-party skills listed in third-party-skills.conf into skills/,
# each with its source repo's LICENSE (and NOTICE, if any), and records the exact
# commits in third-party-skills.lock. Rerun it to update them.
#
# Works in bash on Linux, macOS and Git Bash on Windows. Needs git.
#
#   scripts/update-third-party-skills.sh            update all
#   scripts/update-third-party-skills.sh animate    update only the named skills
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
conf="$root/scripts/third-party-skills.conf"
lock="$root/scripts/third-party-skills.lock"
skills="$root/skills"
only=" $* "

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Skills already managed by this script are listed in the previous lock. Anything
# else in skills/ is ours and must never be overwritten.
old_lock="$tmp/old-lock"
if [[ -f "$lock" ]]; then tr -d '\r' <"$lock" >"$old_lock"; else : >"$old_lock"; fi
is_managed() { grep -qE "^$1 " "$old_lock"; }

new_lock="$tmp/lock"
printf '# Generated by update-third-party-skills.sh. Do not edit.\n# name repo commit path\n' >"$new_lock"

while read -r repo ref path name; do
  [[ -z "${repo:-}" || "$repo" == \#* ]] && continue
  if [[ "$only" != "  " && "$only" != *" $name "* ]]; then
    # Not selected: keep its previous lock line.
    grep -E "^$name " "$old_lock" >>"$new_lock" || true
    continue
  fi

  if [[ -e "$skills/$name" ]] && ! is_managed "$name"; then
    echo "error: skills/$name exists and is not a third-party skill from the lock file, refusing to overwrite" >&2
    exit 1
  fi

  # One checkout per repo and ref.
  dir="$tmp/src/$(printf '%s' "$repo@$ref" | tr -c 'A-Za-z0-9._-' '_')"
  if [[ ! -d "$dir" ]]; then
    git clone --quiet --filter=blob:none --no-checkout "https://github.com/$repo.git" "$dir"
    git -C "$dir" -c advice.detachedHead=false checkout --quiet "$ref"
  fi
  sha="$(git -C "$dir" rev-parse HEAD)"

  if [[ ! -f "$dir/$path/SKILL.md" ]]; then
    echo "error: $repo@$ref has no $path/SKILL.md" >&2
    exit 1
  fi
  if ! tr -d '\r' <"$dir/$path/SKILL.md" | grep -qE "^name: *\"?$name\"? *$"; then
    echo "error: $repo/$path/SKILL.md is not named '$name'" >&2
    exit 1
  fi

  rm -rf "$skills/$name"
  cp -R "$dir/$path" "$skills/$name"
  for f in "$dir"/LICENSE* "$dir"/LICENCE* "$dir"/NOTICE*; do
    [[ -f "$f" ]] || continue
    base="$(basename "$f")"
    case "$base" in
      LICEN[CS]E*) target="LICENSE" ;;
      *) target="NOTICE" ;;
    esac
    [[ -f "$skills/$name/$target" ]] || cp "$f" "$skills/$name/$target"
  done
  if [[ ! -f "$skills/$name/LICENSE" ]]; then
    echo "error: $repo has no LICENSE file, not copying $name" >&2
    rm -rf "$skills/$name"
    exit 1
  fi

  echo "$name $repo $sha $path" >>"$new_lock"
  echo "updated  skills/$name  ($repo@${sha:0:12})"
done < <(tr -d '\r' <"$conf")

mv "$new_lock" "$lock"
echo "Done. Review the changes with git diff before committing."
